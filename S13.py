#Киберпанк: Перехват и анализ сетевого трафика
#Вы — тестировщик службы безопасности, перехватывающий поток
#данных из корпоративной сети. Сырой массив представляет собой «силу
#сигнала» (в децибелах). Значения <= 0 — это зашифрованный мусор и
#битые пакеты. Нужно очистить поток, отсортировать его по силе сигнала и
#разделить на «фоновый шум» и «ценные данные».
raw_signals = [12, -4, 88, 0, 45, 102, -15, 250, 33, 5, 76, 150, 0, -88, 22]
clean = [x for x in raw_signals if x > 0] #очистка
broken = len(raw_signals) - len(clean)
clean.sort() #сортировка(возр)
mid = len(clean) // 2 #дел на две пол
noise = clean[:mid]
data = clean[mid:]
data.reverse()
print("Битых пакетов:", broken)
print("Фоновый шум:", noise)
print("Ценные данные:", data)