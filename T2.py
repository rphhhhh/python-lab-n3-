#Аналитический центр телеметрии роботов-курьеров
#Разработать модуль аналитики для логистического хаба.
#На вход поступает «сырой» поток телеметрии от роботов-курьеров.
#Каждый пакет данных жестко структурирован и представлен кортежем.
#Вам нужно очистить данные, рассчитать дистанцию до базы и распределить
#роботов по статусам, строго соблюдая правила работы с неизменяемыми структурами.
import time
i = 0
while i < 3: print("Загрузка" + "." * (i := i + 1)); time.sleep(0.5)
raw = [(101,10,20,85),(102,-5,10,15),(103,120,50,90),(104,15,15,45),(105,200,0,70),(106,40,40,10),(107,0,0,100)]
data = [(d, x, y, b, (x*x + y*y) ** 0.5) for d, x, y, b in raw if b >= 20]
near = far = data[0]
for t in data:
    near = t if t[4] < near[4] else near
    far = t if t[4] > far[4] else far
    print(f"{t[0]:<6}{t[1]:>6}{t[2]:>6}{t[3]:>5}%{t[4]:>9.2f}  {'Готов к работе' if t[4] <= 50 else 'Требует маршрутизации' if t[4] <= 150 else 'Возврат на базу'}")
print(f"Ближайший: {near[0]}, дальний: {far[0]}")